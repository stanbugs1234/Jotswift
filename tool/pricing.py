"""Writes docs/pricing.md: every product to create in App Store Connect,
Google Play and RevenueCat, with its US price, from the same sources the
content tools use.

  python3 tool/pricing.py

Sources: tool/packs.json (page packs and journals), BOOKS in
tool/make_diary.py (diaries and planners), PACKS in tool/make_stickers.py
and tool/make_covers.py, the paid calendar templates (tool/make_calendar_listings.py),
tool/collections.json plus the Budget
collection, tool/bundles.json, and Jotswift Pro below.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tool"))

import make_calendar_listings  # noqa: E402
import make_covers  # noqa: E402
import make_diary  # noqa: E402
import make_life_planners  # noqa: E402
import make_stickers  # noqa: E402

COLLECTION_PRICE = "2.99"
CALENDAR_TEMPLATE_PRICE = "1.99"
DIARY_YEAR, ACADEMIC_YEAR = 2027, 2026

PRO = [
    ("pro_monthly", "Jotswift Pro, monthly", "Auto-renewing subscription", "2.99 / month"),
    ("pro_yearly", "Jotswift Pro, yearly (7-day free trial)", "Auto-renewing subscription", "19.99 / year"),
    ("pro_lifetime", "Jotswift Pro, lifetime", "Non-consumable", "29.99"),
]


def rows():
    """(section, product id, name, catalog items, price) for every product."""
    out = []
    packs = json.loads((ROOT / "tool" / "packs.json").read_text())["packs"]
    for item, pack in packs.items():
        if pack["unlock"].get("free"):
            continue
        for product in pack["unlock"]["products"]:
            section = "Journals" if pack["category"] == "journals" else "Page packs"
            out.append((section, product, pack["name"], item, pack["price"]))
    for key, book in make_diary.BOOKS.items():
        year = ACADEMIC_YEAR if book.get("start", 1) != 1 else DIARY_YEAR
        item = make_diary.item_id(key, year)
        product = f"planner_{key}_{year}" if book.get("dated", True) else f"pack_{key}"
        name = book["name"] + (f" {item.split('_', 2)[-1].replace('_', '-')}" if book.get("dated", True) else "")
        out.append(("Diaries & planners", product, name, item, book["price"]))
        if make_diary.spans(key):  # also October to December of the next year
            year = DIARY_YEAR - 1
            out.append(("Diaries & planners", f"planner_{key}_{year}",
                        f"{book['name']} Oct {year} - Dec {year + 1}", make_diary.item_id(key, year, span=True),
                        book["price"]))
    for key, make in make_life_planners.PLANNERS.items():
        cfg = make()
        for edition in make_life_planners.editions(key):
            item = make_life_planners.item_id(key, edition)
            name = make_life_planners.listing_name(cfg, edition)
            out.append(("Bestseller planners", make_life_planners.product_id(key, edition), name, item,
                        make_life_planners.PRICES[key]))
    for pid, (name, _, price) in make_stickers.PACKS.items():
        out.append(("Stickers", f"pack_{pid}", name, pid, price))
    for pid, (name, _, _) in make_covers.PACKS.items():
        out.append(("Covers", f"pack_{pid}", name, f"{pid} (12 covers)", "1.99"))
    collections = json.loads((ROOT / "tool" / "collections.json").read_text())["collections"]
    for cid, spec in list(collections.items()) + [("budget", {"name": "Budget"})]:
        out.append(("Collections", f"pack_{cid}", spec["name"], f"{cid} (planner, pages, covers, papers, stickers)",
                    COLLECTION_PRICE))
    bundle_ids = set(json.loads((ROOT / "tool" / "bundles.json").read_text())["bundles"])
    spread_planners = json.loads((ROOT / "tool" / "spreads.json").read_text())["planners"]
    for item, planner in spread_planners.items():
        if planner["unlock"].get("free"):
            continue
        for product in planner["unlock"].get("products", []):  # Pro-only items have none
            if product not in bundle_ids:  # the Life Planner is listed with the bundles
                out.append(("Spread planners", product, planner["name"], item, planner["price"]))
    calendar_products = make_calendar_listings.products()
    for tid, (name, _) in make_calendar_listings.TEMPLATES.items():
        out.append(("Calendar templates", calendar_products[tid], name, f"calendar_{tid}", CALENDAR_TEMPLATE_PRICE))
    bundles = json.loads((ROOT / "tool" / "bundles.json").read_text())["bundles"]
    for product, spec in bundles.items():
        out.append(("Bundles", product, spec["name"], ", ".join(spec["items"]), spec["price"]))
    return out


def main():
    all_rows = rows()
    lines = [
        "# Prices",
        "",
        "Generated by `python3 tool/pricing.py`; edit the sources it names, not this file.",
        "",
        "Every paid item is also included in **Jotswift Pro**. Prices are US dollars; set each in App Store",
        "Connect and Google Play (other countries follow Apple's and Google's price tiers), then add the",
        "product to RevenueCat ([store-setup.md](store-setup.md)). All products except the two Pro",
        "subscriptions are **non-consumable** (bought once, restorable).",
        "",
        "Noteshelf, for comparison (US App Store, 2026): $9.99/month, $29.99 to $39.99/year, $14.99 lifetime;",
        "it doesn't sell templates one at a time.",
        "",
        "## Jotswift Pro",
        "",
        "| Product id | What | Type | Price |",
        "|---|---|---|---|",
    ]
    lines += [f"| `{pid}` | {name} | {kind} | ${price} |" for pid, name, kind, price in PRO]
    sections = []
    for row in all_rows:
        if row[0] not in sections:
            sections.append(row[0])
    for section in sections:
        lines += ["", f"## {section}", "", "| Product id | Name | Unlocks | Price |", "|---|---|---|---|"]
        for sec, product, name, items, price in all_rows:
            if sec == section:
                lines.append(f"| `{product}` | {name} | {items} | ${price} |")
    total = len(all_rows) + len(PRO)
    lines += ["", f"{total} products in all.", ""]
    (ROOT / "docs" / "pricing.md").write_text("\n".join(lines))
    print(f"docs/pricing.md: {total} products")


if __name__ == "__main__":
    main()
